/* BV-Note AI UI fix v3.9.12.8 — additive, reversible */
(()=>{'use strict';
const thread=document.getElementById('ai-ui-thread');
const composer=document.getElementById('ai-chat-composer');
if(!thread)return;
function label(b){return (b.textContent||'').trim()}
function fixCard(card){
 const actions=card.querySelector('.ai-block-actions');if(!actions)return;
 const edit=actions.querySelector('button.ai-ui-edit');
 if(!edit)return;
 actions.classList.add('bv39128-actions');card.classList.add('bv39128-card');
 edit.classList.add('bv39128-edit');
 const menus=[...actions.querySelectorAll('details.bv39125-menu')];
 const menu=menus[0];
 // Remove only redundant menus generated by prior UI patches, not native handlers.
 for(const duplicate of menus.slice(1))duplicate.remove();
 if(menu){
  menu.classList.add('bv39128-menu');
  const choices=menu.querySelector('.bv39125-menu-items');
  if(choices){
   // A single edit/commit control belongs on the card; the menu retains full editor.
   for(const b of [...choices.querySelectorAll('button')]){
    if(b.dataset.bv39127==='edit'||/^(edit|commit)$/i.test(label(b)))b.remove();
    else if(label(b)==='展開編輯'){b.hidden=false;b.style.removeProperty('display')}
   }
  }
 }
 // Earlier patches sometimes leave a standalone full-editor button on the card.
 for(const b of [...actions.querySelectorAll('button')]){
  if(b===edit||b.closest('.bv39125-menu'))continue;
  if(label(b)==='展開編輯')b.classList.add('bv39128-hide');
 }
 // Only hide attachment counter UI, not actual file inputs or stored attachments.
 for(const node of card.querySelectorAll('.ai-ui-block-attachments,.ai-ui-attachments'))node.classList.add('bv39128-hide');
 for(const b of card.querySelectorAll('button')){
  if(/^(?:📎\s*)?(?:附件|區塊附件)\s*[（(]\s*\d+\s*[）)]$/.test(label(b)))b.classList.add('bv39128-hide');
 }
 edit.classList.toggle('bv39128-commit',/commit|完成/i.test(label(edit)));
 edit.classList.toggle('bv39128-editing',!/commit|完成/i.test(label(edit)));
}
function fixComposer(){
 if(!composer)return;
 const toggle=document.getElementById('ai-composer-toggle')||[...composer.querySelectorAll('button')].find(b=>/^(?:[▴▾]\s*)?(?:展開|收合)(?:輸入框|\/收合)?$/.test(label(b)));
 const attach=document.getElementById('ai-attach-button');
 if(!toggle||!attach)return;
 const bar=attach.parentElement;
 if(!bar)return;
 bar.classList.add('bv39128-toolbar');
 if(toggle.parentElement!==bar)bar.insertBefore(toggle,attach);
 else if(toggle.nextElementSibling!==attach)bar.insertBefore(toggle,attach);
 // Keep native click handler and accessibility attributes intact.
}
let busy=false;
function update(){if(busy)return;busy=true;try{for(const card of thread.querySelectorAll('.ai-ui-block'))fixCard(card);fixComposer()}finally{busy=false}}
let scheduled=false;
const observer=new MutationObserver(()=>{if(scheduled)return;scheduled=true;requestAnimationFrame(()=>{scheduled=false;update()})});
observer.observe(thread,{subtree:true,childList:true,characterData:true});
if(composer)observer.observe(composer,{subtree:true,childList:true});
update();
})();
